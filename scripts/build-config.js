#!/usr/bin/env node
// Bundles /config/*.json into js/config-bundle.js so the app works from file:// (no fetch needed).
// Run after editing any file in /config:   node scripts/build-config.js
// CI / pre-commit check:                   node scripts/build-config.js --check
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const files = {
  definitions: 'config/object-definitions.json',
  validation: 'config/validation-rules.json',
  templates: 'config/templates.json',
  fsDefinitions: 'config/fs-definitions.json',
  fsTemplates: 'config/fs-templates.json'
};

const bundle = {};
for (const [key, rel] of Object.entries(files)) {
  bundle[key] = JSON.parse(fs.readFileSync(path.join(root, rel), 'utf8'));
}

const out =
  '// GENERATED by scripts/build-config.js from /config/*.json — do not edit by hand.\n' +
  'window.APB_CONFIG = ' + JSON.stringify(bundle, null, 1) + ';\n';
const target = path.join(root, 'js', 'config-bundle.js');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== out) {
    console.error('js/config-bundle.js is out of date. Run: node scripts/build-config.js');
    process.exit(1);
  }
  console.log('config bundle is up to date');
} else {
  fs.writeFileSync(target, out);
  console.log('wrote js/config-bundle.js');
}
